const STAR = '<svg viewBox="0 0 24 24" width="30" height="30" aria-hidden="true"><path d="M12 2.5l2.94 5.96 6.58.96-4.76 4.64 1.12 6.55L12 17.52l-5.88 3.09 1.12-6.55L2.48 9.42l6.58-.96z"/></svg>';

let lang = localStorage.getItem('lang') === 'ar' ? 'ar' : 'en';
const values = { overall: 0, study_zone: 0, courses: 0 };
let recommend = '';
const scales = [];
const form = document.getElementById('form');
const msg = document.getElementById('msg');

function applyLang() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.title = T[lang].title;
  document.querySelectorAll('[data-i18n]').forEach(el => el.textContent = T[lang][el.dataset.i18n]);
  document.querySelectorAll('[data-i18n-ph]').forEach(el => el.placeholder = T[lang][el.dataset.i18nPh]);
  document.getElementById('langBtn').textContent = T[lang].other_lang;
  scales.forEach(s => s());
  clearError();
}

// ---------- Star scales ----------
document.querySelectorAll('.scale').forEach(scale => {
  const name = scale.dataset.name;
  const required = !!scale.dataset.required;
  const box = scale.querySelector('.stars');
  const label = scale.querySelector('.scale-text');
  const btns = [];

  const paint = n => btns.forEach((b, i) => b.classList.toggle('on', i < n));
  const refresh = () => {
    paint(values[name]);
    label.textContent = values[name] ? T[lang]['rate' + values[name]] : '';
    btns.forEach((b, i) => {
      b.setAttribute('aria-checked', String(values[name] === i + 1));
      b.tabIndex = (values[name] ? values[name] === i + 1 : i === 0) ? 0 : -1;
    });
  };
  const choose = n => { values[name] = n; refresh(); clearError(); };

  for (let i = 1; i <= 5; i++) {
    const b = document.createElement('button');
    b.type = 'button';
    b.setAttribute('role', 'radio');
    b.setAttribute('aria-label', `${i}/5`);
    b.innerHTML = STAR;
    b.onmouseenter = () => { paint(i); label.textContent = T[lang]['rate' + i]; };
    b.onclick = () => choose(!required && values[name] === i ? 0 : i);   // optional ratings can be cleared by clicking again
    b.onkeydown = e => {
      const dir = document.documentElement.dir === 'rtl' ? -1 : 1;
      const step = { ArrowRight: dir, ArrowLeft: -dir, ArrowUp: 1, ArrowDown: -1 }[e.key];
      if (!step) return;
      e.preventDefault();
      const next = Math.min(5, Math.max(1, (values[name] || i) + step));
      choose(next);
      btns[next - 1].focus();
    };
    btns.push(b);
    box.appendChild(b);
  }
  box.onmouseleave = refresh;
  scales.push(refresh);
});

// ---------- Recommend choice ----------
document.querySelectorAll('#recommend button').forEach(b => {
  b.onclick = () => {
    recommend = recommend === b.dataset.value ? '' : b.dataset.value;
    document.querySelectorAll('#recommend button').forEach(x =>
      x.setAttribute('aria-checked', String(x.dataset.value === recommend)));
  };
});

// ---------- Validation ----------
function clearError() {
  msg.textContent = '';
  msg.classList.remove('error');
  form.querySelectorAll('[aria-invalid]').forEach(el => el.removeAttribute('aria-invalid'));
}

function showError(field) {
  clearError();
  msg.textContent = T[lang]['err_' + field] || T[lang].error;
  msg.classList.add('error');
  const el = form.elements[field];
  if (el) { el.setAttribute('aria-invalid', 'true'); el.focus(); }
  else if (field === 'overall') document.querySelector('[data-name="overall"] button').focus();
}

function validate(f) {
  if (f.elements.name.value.trim().split(/\s+/).filter(Boolean).length < 3) return 'name';
  if (!/^\+?\d{7,15}$/.test(f.elements.phone.value.replace(/[\s\-().]/g, ''))) return 'phone';
  const email = f.elements.email.value.trim();
  if (email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) return 'email';
  if (!f.elements.university.value.trim()) return 'university';
  if (!f.elements.study_level.value) return 'study_level';
  if (!values.overall) return 'overall';
  if (!f.elements.consent.checked) return 'consent';
  return null;
}

// ---------- Events ----------
document.getElementById('langBtn').onclick = () => {
  lang = lang === 'en' ? 'ar' : 'en';
  localStorage.setItem('lang', lang);
  applyLang();
};

document.getElementById('againBtn').onclick = () => {
  document.getElementById('thanksCard').hidden = true;
  document.getElementById('formCard').hidden = false;
  window.scrollTo({ top: 0 });
};

form.onsubmit = async e => {
  e.preventDefault();
  const f = e.target;
  const problem = validate(f);
  if (problem) { showError(problem); return; }
  clearError();

  const body = {
    name: f.elements.name.value, phone: f.elements.phone.value, email: f.elements.email.value,
    university: f.elements.university.value, major: f.elements.major.value,
    study_level: f.elements.study_level.value, heard_about: f.elements.heard_about.value,
    comment: f.elements.comment.value, recommend, consent: f.elements.consent.checked,
    website: f.elements.website.value,
    ...values, lang
  };
  const btn = f.querySelector('.submit');
  btn.disabled = true;
  try {
    const r = await fetch('/api/ratings', {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body)
    });
    if (r.status === 429) { msg.textContent = T[lang].tooMany; msg.classList.add('error'); return; }
    if (r.status === 400) { const j = await r.json().catch(() => ({})); showError(j.field); return; }
    if (!r.ok) throw new Error('Server replied ' + r.status);

    f.reset();
    Object.keys(values).forEach(k => values[k] = 0);
    recommend = '';
    document.querySelectorAll('#recommend button').forEach(x => x.setAttribute('aria-checked', 'false'));
    scales.forEach(s => s());
    document.getElementById('formCard').hidden = true;
    document.getElementById('thanksCard').hidden = false;
    window.scrollTo({ top: 0 });
  } catch {
    msg.textContent = T[lang].error; msg.classList.add('error');
  } finally {
    btn.disabled = false;
  }
};

applyLang();
